/**
 * Script per generare automaticamente i wrapper Cloudflare per tutte le API routes
 * Esegui: node scripts/generate-cloudflare-functions.js
 *
 * eslint-disable no-console -- CLI script, console output is expected
 */

import { readdirSync, statSync, writeFileSync, existsSync, mkdirSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const projectRoot = join(__dirname, "..");

const API_DIR = join(projectRoot, "api");
const FUNCTIONS_DIR = join(projectRoot, "functions", "api");

// API da escludere (sono helper o non hanno export default handler)
const EXCLUDE = ["_lib", "admin", "admin.js"];

function getApiFiles() {
  const files = [];

  try {
    const entries = readdirSync(API_DIR);

    for (const entry of entries) {
      const fullPath = join(API_DIR, entry);
      const stat = statSync(fullPath);

      if (stat.isFile() && entry.endsWith(".js") && !EXCLUDE.includes(entry)) {
        files.push(entry);
      }
    }
  } catch (error) {
    console.error("Errore lettura directory API:", error);
    return [];
  }

  return files;
}

function generateWrapper(apiFile) {
  const wrapperContent = `/**
 * Cloudflare Function - ${apiFile.replace(".js", "")} API
 * Wraps the Vercel handler for Cloudflare compatibility
 * Auto-generated by scripts/generate-cloudflare-functions.js
 */

import { createCloudflareHandler } from '../../api/_lib/adapter.js';
import vercelHandler from '../../api/${apiFile}';

export const onRequest = createCloudflareHandler(vercelHandler);
`;

  return wrapperContent;
}

function main() {
  console.log("🔍 Scansione API routes...\n");

  // Crea directory functions/api se non esiste
  if (!existsSync(FUNCTIONS_DIR)) {
    mkdirSync(FUNCTIONS_DIR, { recursive: true });
    console.log("✅ Creata directory:", FUNCTIONS_DIR);
  }

  const apiFiles = getApiFiles();
  console.log(`📦 Trovate ${apiFiles.length} API routes:\n`);

  let created = 0;
  let skipped = 0;

  for (const apiFile of apiFiles) {
    const wrapperPath = join(FUNCTIONS_DIR, apiFile);

    // Skip se esiste già (non sovrascrivere)
    if (existsSync(wrapperPath)) {
      console.log(`⏭️  Skip: ${apiFile} (già esistente)`);
      skipped++;
      continue;
    }

    const wrapperContent = generateWrapper(apiFile);
    writeFileSync(wrapperPath, wrapperContent, "utf8");
    console.log(`✅ Creato: ${apiFile}`);
    created++;
  }

  console.log(`\n📊 Riepilogo:`);
  console.log(`   - Create: ${created}`);
  console.log(`   - Skip: ${skipped}`);
  console.log(`   - Total: ${apiFiles.length}`);
  console.log(`\n✨ Completato!`);
}

main();
