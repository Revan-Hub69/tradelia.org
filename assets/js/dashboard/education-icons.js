/**
 * Render icon helper
 */
export function renderIcon(iconName, size = 18) {
  const icon = EducationIcons[iconName];
  if (!icon) {
    return "";
  }
  return icon.replace(
    'viewBox="0 0 24 24"',
    `viewBox="0 0 24 24" width="${size}" height="${size}"`
  );
}
